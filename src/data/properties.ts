export const featuredProperties = properties.filter(
  (property) => property.featured
);

export const launchProperties = properties.filter(
  (property) => property.isLaunch
);

export const saleProperties = properties.filter(
  (property) => property.purpose === "Comprar"
);

export const rentalProperties = properties.filter(
  (property) => property.purpose === "Alugar"
);

export function getPropertyBySlug(
  slug: string
): Property | undefined {
  return properties.find(
    (property) => property.slug === slug
  );
}

export function getPropertyByCode(
  code: string
): Property | undefined {
  return properties.find(
    (property) =>
      property.code.toLowerCase() === code.toLowerCase()
  );
}

export function formatPrice(price: number): string {
  return new Intl.NumberFormat("pt-BR", {
    style: "currency",
    currency: "BRL",
    maximumFractionDigits: 0,
  }).format(price);
}
